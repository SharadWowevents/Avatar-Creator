let PDFDocument;
try {
  PDFDocument = require('pdfkit');
} catch (e) {
  PDFDocument = null;
  console.warn("[PDF Service] Notice: 'pdfkit' module is not yet installed on this server. Run 'npm install' in the backend directory to enable full 3-page styled PDF dossiers.");
}

/**
 * Minimal standalone valid PDF buffer generator without any external dependencies
 */
function createFallbackPdfBuffer(data) {
  const lbName = (data?.lifeboat?.characterName || 'Lifeboat Avatar').replace(/[()\\]/g, '');
  const ycName = (data?.yacht?.characterName || 'Yacht Avatar').replace(/[()\\]/g, '');
  const title = (data?.title || 'Customer Avatar Dossier').replace(/[()\\]/g, '');

  const textStream = `BT
/F1 18 Tf
40 740 Td
(${title}) Tj
/F1 12 Tf
0 -28 Td
(Lifeboat Avatar: ${lbName}) Tj
0 -20 Td
(Yacht Avatar: ${ycName}) Tj
/F1 10 Tf
0 -30 Td
(Generated by WOW Events Customer Avatar Creator) Tj
0 -20 Td
(Please run 'npm install' on the server to enable high-resolution multi-page visual PDF dossiers.) Tj
ET`;

  const streamLength = Buffer.byteLength(textStream, 'utf8');

  const pdfString = `%PDF-1.4
1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj
2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj
3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj
4 0 obj << /Length ${streamLength} >> stream
${textStream}
endstream
endobj
5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj
xref
0 6
0000000000 65535 f 
0000000010 00000 n 
0000000060 00000 n 
0000000117 00000 n 
0000000244 00000 n 
0000000300 00000 n 
trailer << /Size 6 /Root 1 0 R >>
startxref
400
%%EOF`;

  return Buffer.from(pdfString);
}

/**
 * Generate a clean, executive 3-page PDF dossier buffer from avatar data
 * @param {Object} data - Avatar output data { lifeboat, yacht, bridge, title }
 * @returns {Promise<Buffer>} - Resolves with PDF file Buffer
 */
function generateAvatarPdfBuffer(data) {
  return new Promise((resolve, reject) => {
    try {
      if (!data) {
        return reject(new Error('No avatar data provided for PDF generation'));
      }

      // If pdfkit is not yet installed on this server, gracefully use the zero-dependency fallback PDF
      if (!PDFDocument) {
        return resolve(createFallbackPdfBuffer(data));
      }

      const doc = new PDFDocument({
        size: 'A4',
        margins: { top: 32, bottom: 32, left: 36, right: 36 },
        bufferPages: true,
        info: {
          Title: data.title || 'Customer Avatar Dossier',
          Author: 'WOW Events Customer Avatar Creator',
          Subject: 'Lifeboat & Yacht Customer Avatars with Bridge Strategy',
          Creator: 'Customer Avatar Creator MERN'
        }
      });

      const buffers = [];
      doc.on('data', chunk => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', err => reject(err));

      const pageWidth = 595.28;
      const pageHeight = 841.89;
      const margin = 36;
      const contentWidth = pageWidth - (margin * 2); // 523.28 pt

      // Theme Colors
      const colors = {
        navy: '#13294b',
        ink: '#0f1d2e',
        muted: '#5a6878',
        line: '#d5dde6',
        bgSoft: '#f8fafc',
        life: '#e8590c',
        lifeSoft: '#fde7dc',
        yacht: '#0b7a75',
        yachtSoft: '#d8f0ee',
      };

      // Helper for drawing a header banner on each page
      function drawPageHeader(title, subtitle, pageNum, primaryColor, softBgColor) {
        // Banner card
        doc.roundedRect(margin, 28, contentWidth, 38, 6)
          .fillAndStroke(softBgColor, primaryColor);

        doc.fillColor(primaryColor)
          .font('Helvetica-Bold')
          .fontSize(11)
          .text(title.toUpperCase(), margin + 14, 36, { continued: false });

        doc.fillColor(colors.muted)
          .font('Helvetica')
          .fontSize(9)
          .text(subtitle, margin + 14, 50, { continued: false });

        doc.fillColor(primaryColor)
          .font('Helvetica-Bold')
          .fontSize(10)
          .text(`PAGE ${pageNum} OF 3`, margin + contentWidth - 90, 42, { width: 80, align: 'right' });

        doc.y = 76;
      }

      // Helper for drawing page footer
      function drawPageFooter(pageNum) {
        const footerY = pageHeight - 32;
        doc.strokeColor(colors.line)
          .lineWidth(0.5)
          .moveTo(margin, footerY - 6)
          .lineTo(margin + contentWidth, footerY - 6)
          .stroke();

        doc.fillColor(colors.muted)
          .font('Helvetica')
          .fontSize(8)
          .text('WOW Events • Customer Avatar Creator Dossier', margin, footerY);

        doc.fillColor(colors.muted)
          .font('Helvetica')
          .fontSize(8)
          .text(`Page ${pageNum} of 3`, margin + contentWidth - 60, footerY, { width: 60, align: 'right' });
      }

      // Helper for text sanitization (removes unsupported emoji or unicode characters in standard PDFKit fonts)
      function cleanText(txt) {
        if (!txt) return '';
        return String(txt)
          .replace(/[^\x00-\x7F]/g, ' ') // Strip non-ASCII/emojis for standard PDF Helvetica safety
          .replace(/\s+/g, ' ')
          .trim();
      }

      // -------------------------------------------------------------
      // PAGE 1: LIFEBOAT AVATAR
      // -------------------------------------------------------------
      const lb = data.lifeboat || {};
      drawPageHeader(
        'Lifeboat Customer Avatar',
        'Situation: Urgent, In Crisis, High Pain, Needs Rapid Rescue',
        1,
        colors.life,
        colors.lifeSoft
      );

      // Character Hero Box
      const heroY = doc.y;
      doc.roundedRect(margin, heroY, contentWidth, 54, 6)
        .fillAndStroke('#ffffff', colors.line);

      doc.fillColor(colors.life)
        .font('Helvetica-Bold')
        .fontSize(9)
        .text(`LIFEBOAT ARCHETYPE: ${cleanText(lb.animal || 'RABBIT').toUpperCase()}`, margin + 14, heroY + 10);

      doc.fillColor(colors.navy)
        .font('Helvetica-Bold')
        .fontSize(16)
        .text(cleanText(lb.characterName || 'Rescue Rhea the Restless Rabbit'), margin + 14, heroY + 22);

      doc.fillColor(colors.muted)
        .font('Helvetica-Oblique')
        .fontSize(9)
        .text(cleanText(lb.tagline || 'Ears up, heart racing, ready to bolt at the next bad message.'), margin + 14, heroY + 40);

      doc.y = heroY + 62;

      // Why this animal box
      const whyY = doc.y;
      doc.roundedRect(margin, whyY, contentWidth, 36, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.life)
        .font('Helvetica-Bold')
        .fontSize(9)
        .text(`Why a ${cleanText(lb.animal || 'Rabbit')}?`, margin + 10, whyY + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8.5)
        .text(cleanText(lb.whyAnimal || 'A rabbit senses danger everywhere and is in constant alert mode.'), margin + 10, whyY + 20, { width: contentWidth - 20 });

      doc.y = whyY + 44;

      // Current State vs Desired State
      const stateBoxWidth = (contentWidth - 12) / 2;
      const stateY = doc.y;
      // Current State (red/orange border)
      doc.roundedRect(margin, stateY, stateBoxWidth, 52, 4)
        .fillAndStroke('#fffaf8', colors.life);
      doc.fillColor(colors.life)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('CURRENT STATE (THE PAIN)', margin + 10, stateY + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8)
        .text(cleanText(lb.currentState || 'Vendor dropped the ball; leadership is furious.'), margin + 10, stateY + 20, { width: stateBoxWidth - 20 });

      // Desired State (green/teal border)
      doc.roundedRect(margin + stateBoxWidth + 12, stateY, stateBoxWidth, 52, 4)
        .fillAndStroke('#f6fbfb', colors.yacht);
      doc.fillColor(colors.yacht)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('DESIRED STATE (THE RELIEF)', margin + stateBoxWidth + 22, stateY + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8)
        .text(cleanText(lb.desiredState || 'Walking into the venue seeing everything set, on budget and praised.'), margin + stateBoxWidth + 22, stateY + 20, { width: stateBoxWidth - 20 });

      doc.y = stateY + 60;

      // Stage of Business / Life
      doc.roundedRect(margin, doc.y, contentWidth, 28, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.navy)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('STAGE OF BUSINESS / LIFE: ', margin + 10, doc.y + 9, { continued: true });
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8.5)
        .text(cleanText(lb.stage || 'Mid-career marketing manager under high delivery pressure.'));

      doc.y += 36;

      // 2-Column Grid for Sections
      const colWidth = (contentWidth - 16) / 2;
      const col1X = margin;
      const col2X = margin + colWidth + 16;
      let gridY = doc.y;

      // Column 1: Top 3 Pain Points
      doc.fillColor(colors.life).font('Helvetica-Bold').fontSize(10).text('Top 3 Pain Points', col1X, gridY);
      doc.y += 4;
      const painPoints = Array.isArray(lb.painPoints) ? lb.painPoints : [];
      painPoints.slice(0, 3).forEach((p, idx) => {
        doc.fillColor(colors.life).font('Helvetica-Bold').fontSize(8.5).text(`${idx + 1}. `, col1X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(p), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 1: Buying Behaviour
      doc.y += 6;
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('Buying Behaviour', col1X, doc.y);
      doc.y += 4;
      const buying = Array.isArray(lb.buyingBehaviour) ? lb.buyingBehaviour : [];
      buying.slice(0, 3).forEach(b => {
        doc.fillColor(colors.life).font('Helvetica').fontSize(8.5).text('• ', col1X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(b), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 2: What They Want
      doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(10).text('What They Want', col2X, gridY);
      let col2Y = gridY + 16;
      doc.y = col2Y;
      const wants = Array.isArray(lb.wants) ? lb.wants : [];
      wants.slice(0, 3).forEach(w => {
        doc.fillColor(colors.yacht).font('Helvetica').fontSize(8.5).text('• ', col2X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(w), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 2: Language They Use
      doc.y += 6;
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('Language They Use', col2X, doc.y);
      doc.y += 4;
      const lang = Array.isArray(lb.language) ? lb.language : [];
      lang.slice(0, 3).forEach(l => {
        doc.fillColor(colors.muted).font('Helvetica-Oblique').fontSize(8).text(`"${cleanText(l)}"`, col2X + 6, doc.y, { width: colWidth - 20 });
        doc.y += 3;
      });

      // Next Steps at the bottom of Page 1
      doc.y = Math.max(doc.y, 670);
      doc.roundedRect(margin, doc.y, contentWidth, 54, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.life).font('Helvetica-Bold').fontSize(9.5).text('Recommended Next Steps (Lifeboat Action Plan)', margin + 10, doc.y + 8);
      const steps = Array.isArray(lb.nextSteps) ? lb.nextSteps : [];
      steps.slice(0, 3).forEach((st, idx) => {
        doc.fillColor(colors.life).font('Helvetica-Bold').fontSize(8).text(`${idx + 1}. `, margin + 12, doc.y + 3, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8).text(cleanText(st), { width: contentWidth - 36 });
      });

      drawPageFooter(1);

      // -------------------------------------------------------------
      // PAGE 2: YACHT AVATAR
      // -------------------------------------------------------------
      doc.addPage();
      const yc = data.yacht || {};
      drawPageHeader(
        'Yacht Customer Avatar',
        'Situation: Growing, Doing Well, High Ambition, Seeks Status & Scale',
        2,
        colors.yacht,
        colors.yachtSoft
      );

      // Character Hero Box
      const heroY2 = doc.y;
      doc.roundedRect(margin, heroY2, contentWidth, 54, 6)
        .fillAndStroke('#ffffff', colors.line);

      doc.fillColor(colors.yacht)
        .font('Helvetica-Bold')
        .fontSize(9)
        .text(`YACHT ARCHETYPE: ${cleanText(yc.animal || 'FALCON').toUpperCase()}`, margin + 14, heroY2 + 10);

      doc.fillColor(colors.navy)
        .font('Helvetica-Bold')
        .fontSize(16)
        .text(cleanText(yc.characterName || 'Visionary Victor the Soaring Falcon'), margin + 14, heroY2 + 22);

      doc.fillColor(colors.muted)
        .font('Helvetica-Oblique')
        .fontSize(9)
        .text(cleanText(yc.tagline || 'Scanning the entire horizon from 10,000 feet, ready for the next peak.'), margin + 14, heroY2 + 40);

      doc.y = heroY2 + 62;

      // Why this animal box
      const whyY2 = doc.y;
      doc.roundedRect(margin, whyY2, contentWidth, 36, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.yacht)
        .font('Helvetica-Bold')
        .fontSize(9)
        .text(`Why a ${cleanText(yc.animal || 'Falcon')}?`, margin + 10, whyY2 + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8.5)
        .text(cleanText(yc.whyAnimal || 'Falcons fly high above the noise, spotting strategic opportunities early.'), margin + 10, whyY2 + 20, { width: contentWidth - 20 });

      doc.y = whyY2 + 44;

      // Current State vs Desired State
      const stateY2 = doc.y;
      doc.roundedRect(margin, stateY2, stateBoxWidth, 52, 4)
        .fillAndStroke('#f8fafc', colors.line);
      doc.fillColor(colors.muted)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('CURRENT SUCCESS BASELINE', margin + 10, stateY2 + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8)
        .text(cleanText(yc.currentState || 'Events are successful, but they want an industry benchmark.'), margin + 10, stateY2 + 20, { width: stateBoxWidth - 20 });

      doc.roundedRect(margin + stateBoxWidth + 12, stateY2, stateBoxWidth, 52, 4)
        .fillAndStroke('#f6fbfb', colors.yacht);
      doc.fillColor(colors.yacht)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('DESIRED ASPIRATIONAL PEAK', margin + stateBoxWidth + 22, stateY2 + 8);
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8)
        .text(cleanText(yc.desiredState || 'A flagship annual brand property that sets the gold standard.'), margin + stateBoxWidth + 22, stateY2 + 20, { width: stateBoxWidth - 20 });

      doc.y = stateY2 + 60;

      // Stage of Business / Life
      doc.roundedRect(margin, doc.y, contentWidth, 28, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.navy)
        .font('Helvetica-Bold')
        .fontSize(8.5)
        .text('STAGE OF BUSINESS / LIFE: ', margin + 10, doc.y + 9, { continued: true });
      doc.fillColor(colors.ink)
        .font('Helvetica')
        .fontSize(8.5)
        .text(cleanText(yc.stage || 'Established enterprise leader aiming for brand dominance.'));

      doc.y += 36;

      // 2-Column Grid
      let gridY2 = doc.y;

      // Column 1: Top 3 Pain Points / Growth Bottlenecks
      doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(10).text('Top 3 Ambition Drivers & Needs', col1X, gridY2);
      doc.y += 4;
      const yachtPains = Array.isArray(yc.painPoints) ? yc.painPoints : [];
      yachtPains.slice(0, 3).forEach((p, idx) => {
        doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(8.5).text(`${idx + 1}. `, col1X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(p), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 1: Buying Behaviour
      doc.y += 6;
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('Buying Behaviour', col1X, doc.y);
      doc.y += 4;
      const yachtBuying = Array.isArray(yc.buyingBehaviour) ? yc.buyingBehaviour : [];
      yachtBuying.slice(0, 3).forEach(b => {
        doc.fillColor(colors.yacht).font('Helvetica').fontSize(8.5).text('• ', col1X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(b), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 2: What They Want
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('What They Want', col2X, gridY2);
      doc.y = gridY2 + 16;
      const yachtWants = Array.isArray(yc.wants) ? yc.wants : [];
      yachtWants.slice(0, 3).forEach(w => {
        doc.fillColor(colors.yacht).font('Helvetica').fontSize(8.5).text('• ', col2X, doc.y, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(w), { width: colWidth - 16 });
        doc.y += 2;
      });

      // Column 2: Language They Use
      doc.y += 6;
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('Language They Use', col2X, doc.y);
      doc.y += 4;
      const yachtLang = Array.isArray(yc.language) ? yc.language : [];
      yachtLang.slice(0, 3).forEach(l => {
        doc.fillColor(colors.muted).font('Helvetica-Oblique').fontSize(8).text(`"${cleanText(l)}"`, col2X + 6, doc.y, { width: colWidth - 20 });
        doc.y += 3;
      });

      // Next Steps at the bottom of Page 2
      doc.y = Math.max(doc.y, 670);
      doc.roundedRect(margin, doc.y, contentWidth, 54, 4)
        .fillAndStroke(colors.bgSoft, colors.line);
      doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(9.5).text('Recommended Next Steps (Yacht Growth Plan)', margin + 10, doc.y + 8);
      const yachtSteps = Array.isArray(yc.nextSteps) ? yc.nextSteps : [];
      yachtSteps.slice(0, 3).forEach((st, idx) => {
        doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(8).text(`${idx + 1}. `, margin + 12, doc.y + 3, { continued: true });
        doc.fillColor(colors.ink).font('Helvetica').fontSize(8).text(cleanText(st), { width: contentWidth - 36 });
      });

      drawPageFooter(2);

      // -------------------------------------------------------------
      // PAGE 3: HOW YOU SERVE BOTH (THE STRATEGIC BRIDGE)
      // -------------------------------------------------------------
      doc.addPage();
      const br = data.bridge || {};
      drawPageHeader(
        'Strategic Offer Architecture',
        'How to Serve Both: Moving Clients from Emergency Rescue to Retainer Mastery',
        3,
        colors.navy,
        '#eef2f6'
      );

      // Headline Card
      const headY = doc.y;
      doc.roundedRect(margin, headY, contentWidth, 48, 6)
        .fillAndStroke('#ffffff', colors.line);
      doc.fillColor(colors.muted).font('Helvetica').fontSize(8.5).text('STRATEGIC HEADLINE', margin + 14, headY + 8);
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(14).text(cleanText(br.headline || 'From Panic Room to Penthouse: Two Offers, One Trusted Partner'), margin + 14, headY + 22, { width: contentWidth - 28 });

      doc.y = headY + 58;

      // Two Offer Lanes (Side by side)
      const laneWidth = (contentWidth - 14) / 2;
      const laneY = doc.y;

      // Lane 1: Lifeboat Offer
      doc.roundedRect(margin, laneY, laneWidth, 120, 6)
        .fillAndStroke('#fffaf8', colors.life);
      doc.fillColor(colors.life).font('Helvetica-Bold').fontSize(11).text('LIFEBOAT OFFER (RESCUE)', margin + 12, laneY + 12);
      doc.fillColor(colors.muted).font('Helvetica-Oblique').fontSize(8).text('Fixed-scope emergency sprint', margin + 12, laneY + 26);
      doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(br.lifeboatOffer || 'Rapid response rescue package with clear pricing, fixed 48-hour turnarounds, and direct daily leadership updates.'), margin + 12, laneY + 42, { width: laneWidth - 24 });

      // Lane 2: Yacht Offer
      doc.roundedRect(margin + laneWidth + 14, laneY, laneWidth, 120, 6)
        .fillAndStroke('#f6fbfb', colors.yacht);
      doc.fillColor(colors.yacht).font('Helvetica-Bold').fontSize(11).text('YACHT OFFER (TRANSFORMATION)', margin + laneWidth + 26, laneY + 12);
      doc.fillColor(colors.muted).font('Helvetica-Oblique').fontSize(8).text('Strategic annual retainer partner', margin + laneWidth + 26, laneY + 26);
      doc.fillColor(colors.ink).font('Helvetica').fontSize(8.5).text(cleanText(br.yachtOffer || 'Comprehensive annual brand experience architecture, dedicated concept lab, and multi-event strategic alignment.'), margin + laneWidth + 26, laneY + 42, { width: laneWidth - 24 });

      doc.y = laneY + 132;

      // The Transformation Journey (Ladder)
      doc.roundedRect(margin, doc.y, contentWidth, 230, 6)
        .fillAndStroke(colors.bgSoft, colors.line);

      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(12).text('The Lifeboat → Yacht Journey Ladder', margin + 14, doc.y + 12);
      doc.fillColor(colors.muted).font('Helvetica').fontSize(8.5).text('How rescue clients naturally transition into long-term strategic relationships:', margin + 14, doc.y + 26);

      let stepY = doc.y + 44;
      const journey = Array.isArray(br.journey) ? br.journey : [
        { tag: 'Rescue', text: 'You resolve an urgent high-stakes problem that other vendors dropped.' },
        { tag: 'Debrief', text: 'You present a root-cause breakdown of why the panic occurred and how to avoid it.' },
        { tag: 'Bridge', text: 'You architect a proactive roadmap for the remainder of their fiscal year.' },
        { tag: 'Retainer', text: 'The client signs an annual strategic retainer to guarantee peace of mind.' }
      ];

      journey.forEach((step, idx) => {
        // Tag badge
        const badgeColor = idx === 0 ? colors.life : idx === journey.length - 1 ? colors.yacht : colors.navy;
        doc.roundedRect(margin + 16, stepY, 68, 22, 4)
          .fillAndStroke(badgeColor, badgeColor);
        doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(8).text(cleanText(step.tag || `Step ${idx + 1}`).toUpperCase(), margin + 18, stepY + 6, { width: 64, align: 'center' });

        // Step text
        doc.fillColor(colors.ink).font('Helvetica').fontSize(9).text(cleanText(step.text || ''), margin + 94, stepY + 4, { width: contentWidth - 110 });

        stepY += 36;
      });

      doc.y = stepY + 10;

      // Strategic Core Message
      const msgY = Math.max(doc.y, 640);
      doc.roundedRect(margin, msgY, contentWidth, 68, 6)
        .fillAndStroke('#ffffff', colors.navy);
      doc.fillColor(colors.navy).font('Helvetica-Bold').fontSize(10).text('STRATEGIC SUMMARY MESSAGE', margin + 14, msgY + 10);
      doc.fillColor(colors.ink).font('Helvetica-Oblique').fontSize(9.5).text(
        `"${cleanText(br.message || 'We step in when you are in trouble to earn your trust; we stay when you are thriving to fuel your ambition.')}"`,
        margin + 14,
        msgY + 26,
        { width: contentWidth - 28 }
      );

      drawPageFooter(3);

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

